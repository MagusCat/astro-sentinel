-- ── Funciones de membresía ──────────────────────────────────────────────────
-- 20260914090100 las recrea con search_path fijo y mueve las cron a `private`.
CREATE FUNCTION public.expire_active_memberships_cron() RETURNS void
LANGUAGE plpgsql SECURITY DEFINER AS $$
BEGIN
  UPDATE memberships SET status = 'expired'
  WHERE status = 'active' AND end_date::date < CURRENT_DATE;
END;
$$;

CREATE FUNCTION public.unfreeze_membership(p_membership_id uuid) RETURNS date
LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE
  v_old RECORD;
  v_new_end_date DATE;
BEGIN
  SELECT * INTO v_old FROM memberships WHERE id = p_membership_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Membresía no encontrada.'; END IF;
  IF v_old.status != 'frozen' THEN RAISE EXCEPTION 'La membresía no está congelada.'; END IF;

  v_new_end_date := CURRENT_DATE + COALESCE(v_old.remaining_days, 0);

  INSERT INTO memberships (payment_id, client_id, class_plan_id, amount_paid,
    start_date, end_date, status, remaining_days, frozen_days, created_at)
  VALUES (v_old.payment_id, v_old.client_id, v_old.class_plan_id, v_old.amount_paid,
    CURRENT_DATE, v_new_end_date, 'active', 0, 0, NOW());

  UPDATE memberships SET status = 'transferred', frozen_days = 0 WHERE id = p_membership_id;
  RETURN v_new_end_date;
END;
$$;

CREATE FUNCTION public.process_frozen_memberships_cron() RETURNS void
LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE r RECORD;
BEGIN
  UPDATE memberships SET frozen_days = GREATEST(0, frozen_days - 1)
  WHERE status = 'frozen' AND frozen_days > 0;
  FOR r IN SELECT id FROM memberships WHERE status = 'frozen' AND frozen_days = 0 LOOP
    PERFORM unfreeze_membership(r.id);
  END LOOP;
END;
$$;

CREATE FUNCTION public.freeze_membership(p_membership_id uuid, p_target_date date) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE
  v_membership RECORD;
  v_class_id UUID;
  v_has_future BOOLEAN;
BEGIN
  IF p_target_date <= CURRENT_DATE THEN
    RAISE EXCEPTION 'La fecha de reactivación debe ser posterior a hoy.';
  END IF;

  SELECT id, end_date, status, client_id, class_plan_id INTO v_membership
  FROM memberships WHERE id = p_membership_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Membresía no encontrada.'; END IF;
  IF v_membership.status != 'active' THEN
    RAISE EXCEPTION 'Solo se pueden congelar membresías activas.';
  END IF;

  SELECT class_id INTO v_class_id FROM class_plans WHERE id = v_membership.class_plan_id;
  IF v_class_id IS NOT NULL THEN
    SELECT EXISTS (
      SELECT 1 FROM memberships m JOIN class_plans cp ON m.class_plan_id = cp.id
      WHERE m.client_id = v_membership.client_id AND m.status = 'active'
        AND cp.class_id = v_class_id AND m.start_date > CURRENT_DATE
        AND m.id != p_membership_id
    ) INTO v_has_future;
    IF v_has_future THEN
      RAISE EXCEPTION 'No se puede pausar si hay membresías en cola.';
    END IF;
  END IF;

  UPDATE memberships
  SET status = 'frozen',
      remaining_days = GREATEST(0, v_membership.end_date - CURRENT_DATE),
      frozen_days = p_target_date - CURRENT_DATE
  WHERE id = p_membership_id;
END;
$$;

-- ── RPC de productos (versión previa) ───────────────────────────────────────
-- 20260621174620 hace REVOKE sobre estas firmas antes de recrearlas, así que
-- tienen que existir. Sus cuerpos los reemplazan las migraciones siguientes.
CREATE FUNCTION public.adjust_product_stock(p_product_id uuid, p_user_id uuid, p_quantity integer, p_type text)
RETURNS integer LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE
  v_previous_stock integer;
  v_new_stock integer;
BEGIN
  SELECT current_stock INTO v_previous_stock FROM inventory WHERE product_id = p_product_id FOR UPDATE;
  IF p_type = 'ADD' THEN v_new_stock := v_previous_stock + p_quantity;
  ELSIF p_type = 'SET' THEN v_new_stock := p_quantity;
  ELSE RAISE EXCEPTION 'Tipo de ajuste no soportado';
  END IF;

  UPDATE inventory SET current_stock = v_new_stock, last_updated = now() WHERE product_id = p_product_id;
  INSERT INTO inventory_movements (product_id, user_id, movement_type, quantity, previous_stock, new_stock)
  VALUES (p_product_id, p_user_id, p_type, v_new_stock - v_previous_stock, v_previous_stock, v_new_stock);
  RETURN v_new_stock;
END;
$$;

CREATE FUNCTION public.process_product_checkout(p_client_id uuid, p_user_id uuid, p_payment_method text, p_total_amount numeric, p_items jsonb)
RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE
  v_payment_id uuid;
  v_item RECORD;
  v_current_stock integer;
BEGIN
  INSERT INTO payments (client_id, user_id, total_amount, payment_method, category, metadata, processed_by)
  VALUES (p_client_id, p_user_id, p_total_amount, p_payment_method, 'PRODUCT', p_items, p_user_id)
  RETURNING id INTO v_payment_id;

  FOR v_item IN SELECT * FROM jsonb_to_recordset(p_items) AS x(product_id uuid, quantity integer) LOOP
    SELECT current_stock INTO v_current_stock FROM inventory WHERE product_id = v_item.product_id FOR UPDATE;
    IF v_current_stock < v_item.quantity THEN
      RAISE EXCEPTION 'Stock insuficiente para producto %', v_item.product_id;
    END IF;
    UPDATE inventory SET current_stock = current_stock - v_item.quantity, last_updated = now()
    WHERE product_id = v_item.product_id;
    INSERT INTO inventory_movements (product_id, user_id, movement_type, quantity, previous_stock, new_stock)
    VALUES (v_item.product_id, p_user_id, 'SALE', -v_item.quantity, v_current_stock, v_current_stock - v_item.quantity);
  END LOOP;

  RETURN v_payment_id;
END;
$$;

-- ── Vistas ──────────────────────────────────────────────────────────────────
CREATE VIEW public.vw_active_memberships WITH (security_invoker = on) AS
  SELECT m.id AS membership_id, c.full_name AS client_name, cl.name AS class_name,
         cp.plan_name, m.status, m.start_date, m.end_date,
         (m.end_date - CURRENT_DATE) AS days_remaining
    FROM memberships m
    JOIN clients c      ON m.client_id = c.id
    JOIN class_plans cp ON m.class_plan_id = cp.id
    JOIN classes cl     ON cp.class_id = cl.id
   WHERE m.status = 'active' AND c.is_active
     AND m.start_date <= CURRENT_DATE AND m.end_date >= CURRENT_DATE;

CREATE VIEW public.vw_class_headcounts WITH (security_invoker = on) AS
  SELECT cl.name AS class_name, count(DISTINCT c.id) AS active_students
    FROM classes cl
    LEFT JOIN class_plans cp ON cl.id = cp.class_id AND cp.is_active
    LEFT JOIN memberships m  ON cp.id = m.class_plan_id AND m.status = 'active' AND m.end_date >= CURRENT_DATE
    LEFT JOIN clients c      ON m.client_id = c.id AND c.is_active
   WHERE cl.is_active
   GROUP BY cl.id, cl.name
   ORDER BY count(DISTINCT c.id) DESC;

CREATE VIEW public.vw_client_status WITH (security_invoker = on) AS
  SELECT DISTINCT ON (c.id)
         c.id, c.full_name, c.email, c.phone_number, c.registration_source, c.is_active, c.created_at,
         m.id IS NOT NULL AS has_active_membership,
         m.status AS current_membership_status,
         p.plan_name AS current_plan_name,
         cls.name AS current_class_name
    FROM clients c
    LEFT JOIN memberships m ON c.id = m.client_id AND m.status IN ('active', 'frozen')
    LEFT JOIN class_plans p ON m.class_plan_id = p.id
    LEFT JOIN classes cls   ON p.class_id = cls.id
   WHERE c.is_active
   ORDER BY c.id,
     CASE m.status WHEN 'active' THEN 1 WHEN 'frozen' THEN 2 ELSE 3 END,
     m.end_date DESC NULLS LAST;

CREATE VIEW public.vw_daily_revenue WITH (security_invoker = on) AS
  SELECT date(p.transaction_date) AS payment_date, p.payment_method, u.full_name AS user_name,
         count(p.id) AS total_transactions, sum(p.total_amount) AS total_revenue
    FROM payments p
    LEFT JOIN users u ON p.user_id = u.id
   WHERE u.is_active = true
   GROUP BY date(p.transaction_date), p.payment_method, u.full_name
   ORDER BY date(p.transaction_date) DESC;

CREATE VIEW public.vw_dashboard_stats WITH (security_invoker = on) AS
  SELECT (SELECT count(*) FROM vw_active_memberships) AS active_memberships_count,
         (SELECT count(*) FROM classes WHERE is_active) AS total_classes_count,
         (SELECT count(*) FROM clients WHERE is_active) AS total_clients_count,
         (SELECT COALESCE(sum(total_amount), 0) FROM payments
           WHERE date(transaction_date) = CURRENT_DATE) AS daily_revenue;

CREATE VIEW public.vw_memberships_extended WITH (security_invoker = on) AS
  SELECT m.id, m.client_id, c.full_name AS client_name, c.email AS client_email,
         m.class_plan_id, p.plan_name, cls.name AS class_name, m.status,
         m.start_date, m.end_date, m.remaining_days, m.created_at
    FROM memberships m
    JOIN clients c      ON m.client_id = c.id
    JOIN class_plans p  ON m.class_plan_id = p.id
    JOIN classes cls    ON p.class_id = cls.id;

CREATE VIEW public.vw_payments_extended WITH (security_invoker = on) AS
  SELECT DISTINCT ON (c.id)
         p.id, p.client_id, c.full_name AS client_name, c.email AS client_email,
         p.user_id, u.full_name AS user_name, u.role AS user_role,
         p.total_amount, p.payment_method, p.transaction_date, m.class_plan_id
    FROM payments p
    JOIN clients c     ON p.client_id = c.id
    JOIN memberships m ON p.id = m.payment_id
    LEFT JOIN users u  ON p.user_id = u.id;

